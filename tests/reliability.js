const assert = require('node:assert/strict');
const { call } = require('./helpers');
const handler = require('../api/game');
(async () => {
  const host = (await call(handler, { action: 'create', name: 'Host' })).j;
  const guest = (await call(handler, { action: 'join', code: host.code, name: 'Guest' })).j;
  const post = async (seat, action, data = {}) => call(handler, { round:(await get(seat)).j.round, action, code: host.code, pid: seat.meId, tok: seat.tok, ...data });
  const get = (seat) => call(handler, null, { code: host.code, pid: seat.meId, f: '1' }, { 'x-tok': seat.tok });
  assert.equal(host.recoveryCode.length, 24);
  assert.ok(!JSON.stringify(host.players).includes(host.recoveryCode), 'recovery code is private');
  const purchase = { kind: 'gift', key: 'tomato', requestId: 'purchase_0000000001' };
  const one = await post(host, 'buy', purchase);
  const replay = await post(host, 'buy', purchase);
  assert.equal(replay.s, 200);
  assert.equal(replay.j.version, one.j.version);
  assert.equal(replay.j.wallet.pts, 15);
  assert.equal(replay.j.wallet.gifts.tomato, 3, 'retry cannot buy twice');
  assert.equal((await post(host, 'buy', { ...purchase, key: 'rose' })).s, 409, 'request ID cannot change meaning');
  assert.equal((await post(host, 'buy', { ...purchase, requestId: 'bad' })).s, 400);
  globalThis.__seen.get(host.code)[host.meId] = Date.now() - 180000;
  assert.equal((await call(handler, { action: 'join', code: host.code, name: 'Host' })).s, 409, 'inactivity cannot expose the host seat');
  await post(host, 'release', { target: guest.meId });
  assert.equal((await call(handler, { action: 'join', code: host.code, name: 'Guest' })).s, 409, 'inactive seat still needs proof');
  assert.equal((await call(handler, { action: 'join', code: host.code, name: 'Guest', recoveryCode: 'incorrect' })).s, 409);
  const staleRoom = JSON.stringify(globalThis.__rooms.get(host.code));
  const recoverRequest = { action: 'join', code: host.code, name: 'Guest', recoveryCode: guest.recoveryCode, requestId: 'recover_seat_000001' };
  const recovered = (await call(handler, recoverRequest)).j;
  const repeatRecovery = (await call(handler, recoverRequest)).j;
  assert.equal(repeatRecovery.tok, recovered.tok, 'recovery retry returns the same new token');
  assert.equal(repeatRecovery.version, recovered.version);
  assert.equal(recovered.meId, guest.meId);
  assert.notEqual(recovered.tok, guest.tok);
  assert.notEqual(recovered.recoveryCode, guest.recoveryCode);
  assert.equal((await get(guest)).s, 404, 'old token invalidated');
  assert.equal((await call(handler, { action: 'join', code: host.code, name: 'Guest', recoveryCode: guest.recoveryCode })).s, 409, 'old recovery code invalidated');
  globalThis.__roomCache.set(host.code, { at: Date.now(), json: staleRoom });
  assert.equal((await call(handler, null, { code: host.code, pid: recovered.meId }, { 'x-tok': recovered.tok })).s, 200, 'a stale instance cache cannot reject the recovered token');
  assert.equal((await get(recovered)).s, 200);
  globalThis.__predOff = true;
  await post(host, 'deal');
  for (const seat of [host, recovered]) {
    let view = (await get(seat)).j;
    for (let slot = 0; slot < 7; slot++) await post(seat, 'place', { card: view.hand[slot], slot });
    await post(seat, 'ready', { ready: true });
  }
  const flip = { slot: 0, requestId: 'flip_retry_00000001' };
  const flipped = await post(host, 'flip', flip);
  const again = await post(host, 'flip', flip);
  assert.equal(again.j.version, flipped.j.version);
  assert.equal(again.j.players.find((p) => p.id === host.meId).board[0].up, true, 'toggle is applied once');
  console.log('reliability and recovery ok');
})().catch((error) => { console.error(error); process.exitCode = 1; });
