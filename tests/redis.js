const assert = require('node:assert/strict');
const { call, startRedis } = require('./helpers');
(async () => {
  const redis = await startRedis();
  try {
    process.env.UPSTASH_REDIS_REST_URL = redis.url;
    process.env.UPSTASH_REDIS_REST_TOKEN = 'local-test';
    const handler = require('../api/game');
    const host = (await call(handler, { action: 'create', name: 'Host' })).j;
    assert.ok(host.code);
    const results = await Promise.all(Array.from({ length: 11 }, (_, i) => call(handler, { action: 'join', code: host.code, name: 'P' + i })));
    assert.ok(results.every((r) => r.s === 200), 'concurrent joins succeed after CAS retries');
    const get = (seat) => call(handler, null, { code: host.code, pid: seat.meId, f: '1' }, { 'x-tok': seat.tok });
    const post = (seat, action, data = {}) => call(handler, { action, code: host.code, pid: seat.meId, tok: seat.tok, ...data });
    assert.equal((await get(host)).j.players.length, 12, 'no player lost to concurrent writes');
    assert.equal((await call(handler, { action: 'join', code: host.code, name: 'Full' })).s, 409);
    const ttl = await redis.client.ttl('room:' + host.code);
    assert.ok(ttl > 43000 && ttl <= 43200, 'room TTL is set by the real Lua script');
    await post(host, 'deal');
    const seats = [host, ...results.map((r) => r.j)];
    const hands = await Promise.all(seats.map(get));
    const moves = await Promise.all(seats.map((seat, i) => post(seat, 'place', { card: hands[i].j.hand[0], slot: 0, requestId: 'parallel_move_00000' + i })));
    assert.ok(moves.every((r) => r.s === 200));
    assert.ok((await get(host)).j.players.every((p) => p.board[0]), 'every simultaneous move persists');
    const buy = { kind: 'gift', key: 'tomato', requestId: 'redis_purchase_0001' };
    const concurrentReplay = await Promise.all([post(host, 'buy', buy), post(host, 'buy', buy)]);
    assert.ok(concurrentReplay.every((r) => r.s === 200));
    assert.equal((await get(host)).j.wallet.gifts.tomato, 3, 'concurrent duplicate applies once');
    redis.fault.dropNextWrite = true;
    const uncertain = { kind: 'gift', key: 'rose', requestId: 'lost_response_00001' };
    assert.equal((await post(host, 'buy', uncertain)).s, 503, 'commit succeeded but response was lost');
    const restored = await post(host, 'buy', uncertain);
    assert.equal(restored.s, 200);
    assert.equal(restored.j.wallet.gifts.rose, 3, 'retry after uncertain write does not spend twice');
    assert.equal(restored.j.wallet.pts, 5);
    const staleRoom = await redis.client.get('room:' + host.code);
    const recoverRequest = { action: 'join', code: host.code, name: 'Host', recoveryCode: host.recoveryCode, requestId: 'redis_recover_00001' };
    redis.fault.dropNextWrite = true;
    assert.equal((await call(handler, recoverRequest)).s, 503);
    const recovery = await call(handler, recoverRequest);
    assert.equal(recovery.s, 200, 'recovery works in a full Redis-backed room');
    assert.equal((await get(host)).s, 404);
    globalThis.__roomCache.set(host.code, { at: Date.now(), json: staleRoom });
    const cachedRecovery = await call(handler, null, { code: host.code, pid: recovery.j.meId }, { 'x-tok': recovery.j.tok });
    assert.equal(cachedRecovery.s, 200, 'recovered token survives a stale server cache');
    assert.equal((await get(recovery.j)).s, 200);
    redis.fault.unavailable = true;
    assert.equal((await get(recovery.j)).s, 503, 'storage errors are retryable and do not reveal internals');
    redis.fault.unavailable = false;
    redis.fault.stall = true;
    const started = Date.now();
    assert.equal((await get(recovery.j)).s, 503);
    assert.ok(Date.now() - started < 5000, 'stalled Redis read has a bounded deadline');
    redis.fault.stall = false;
    assert.equal((await get(recovery.j)).s, 200, 'storage recovery restores the room');
    console.log('real Redis concurrency, replay, recovery, failure and timeout tests ok');
  } finally { await redis.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
