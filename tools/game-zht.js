// Optional authoring tool: OPENCC_PATH=/path/to/opencc-js node tools/game-zht.js
// Production serves the generated dictionary and does not need OpenCC installed.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const convert=require(process.env.OPENCC_PATH || 'opencc-js').Converter({from:'cn',to:'twp'});
let dict;vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../public/game-i18n-zh.js'),'utf8'),{window:{GAME_I18N_REGISTER:(code,value)=>dict=value}});
const exact=Object.fromEntries(Object.entries(dict.exact).map(([key,value])=>[key,convert(value)]));
const patterns=dict.patterns.map(([key,value])=>[key,convert(value)]);
fs.writeFileSync(path.join(__dirname,'../public/game-i18n-zht.js'),'// Traditional Chinese. Generated by tools/game-zht.js; edit game-i18n-zh.js.\nwindow.GAME_I18N_REGISTER("zht",'+JSON.stringify({exact,patterns})+');\n');
console.log(Object.keys(exact).length,'strings;',patterns.length,'patterns');
